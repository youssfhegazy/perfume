const DICTS = { en, ar } as const;

export type Dictionary = Dict;

export function getDictionary(locale: Locale): Dictionary {
  return DICTS[locale];
}

/**
 * Pick the plural form for `n` in `locale`. English needs one/other; Arabic
 * has six categories and gets them wrong if you just append a suffix.
 */
export function plural(forms: PluralForms, n: number, locale: Locale) {
  const rule = new Intl.PluralRules(locale === "ar" ? "ar-EG" : "en-US").select(n);
  return forms[rule] ?? forms.other ?? "";
}

/** Replace {token} placeholders. */
export function t(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) =>
    k in vars ? String(vars[k]) : `{${k}}`,
  );
}
